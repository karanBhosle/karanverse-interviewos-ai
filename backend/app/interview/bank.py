def questions_for_mode(mode: str, difficulty: str | None = None) -> list[dict[str, Any]]:
    selected = [q for q in QUESTION_BANK if mode in q["modes"] or mode == "mixed" and "mixed" in q["modes"]]
    if difficulty and difficulty != "adaptive":
        preferred = [q for q in selected if q["difficulty"] == difficulty]
        if preferred:
            selected = preferred + [q for q in selected if q not in preferred]
    return selected


def get_question(question_key: str) -> dict[str, Any] | None:
    return next((q for q in QUESTION_BANK if q["question_key"] == question_key), None)


def dimensions_for(question: dict[str, Any]) -> list[dict[str, Any]]:
    return DIMENSION_PRESETS[question.get("rubric_type", "technical")]
